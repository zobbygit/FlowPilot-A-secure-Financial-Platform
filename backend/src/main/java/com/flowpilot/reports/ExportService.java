package com.flowpilot.reports;

import com.flowpilot.reports.ReportService.ReportTable;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.List;
import org.springframework.stereotype.Service;

@Service
public class ExportService {

    /** RFC 4180 quoting plus spreadsheet-formula neutralisation (cells starting with = + - @ are prefixed). */
    public byte[] csv(ReportTable t) {
        StringBuilder sb = new StringBuilder("\uFEFF");
        sb.append(line(List.of(t.title() + " (" + t.currency() + ")" + (t.from() != null ? " " + t.from() + " to " + t.to() : "")))).append('\n');
        sb.append(line(t.columns())).append('\n');
        for (List<String> r : t.rows()) sb.append(line(r)).append('\n');
        for (String n : t.notes()) sb.append(line(List.of("Note: " + n))).append('\n');
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    static String line(List<String> cells) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < cells.size(); i++) {
            if (i > 0) sb.append(',');
            String c = cells.get(i) == null ? "" : cells.get(i);
            if (!c.isEmpty() && "=+-@\t\r".indexOf(c.charAt(0)) >= 0 && !c.matches("-?\\d+(\\.\\d+)?")) c = "'" + c;   // negative numbers are legitimate values
            sb.append('"').append(c.replace("\"", "\"\"")).append('"');
        }
        return sb.toString();
    }

    public byte[] pdf(ReportTable t, String ownerName) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Document doc = new Document(PageSize.A4, 40, 40, 48, 48);
            PdfWriter.getInstance(doc, out);
            doc.open();
            Font h1 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18), small = FontFactory.getFont(FontFactory.HELVETICA, 9), body = FontFactory.getFont(FontFactory.HELVETICA, 10),
                    bold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10);
            doc.add(new Paragraph("FlowPilot — " + t.title(), h1));
            doc.add(new Paragraph((t.from() != null ? "Period: " + t.from() + " to " + t.to() + " · " : "") + "Currency: " + t.currency() + " · Prepared for " + ownerName + " on " + LocalDate.now(), small));
            doc.add(new Paragraph(" "));
            PdfPTable table = new PdfPTable(t.columns().size());
            table.setWidthPercentage(100);
            for (String c : t.columns()) { PdfPCell cell = new PdfPCell(new Phrase(c, bold)); cell.setPadding(5); table.addCell(cell); }
            for (List<String> r : t.rows()) for (int i = 0; i < r.size(); i++) {
                PdfPCell cell = new PdfPCell(new Phrase(r.get(i), body)); cell.setPadding(4);
                if (i > 0) cell.setHorizontalAlignment(Element.ALIGN_RIGHT);
                table.addCell(cell);
            }
            doc.add(table);
            doc.add(new Paragraph(" "));
            for (String n : t.notes()) doc.add(new Paragraph("• " + n, small));
            doc.add(new Paragraph(" "));
            doc.add(new Paragraph("This is a personal financial summary generated by FlowPilot. It is not an official tax document or a legally certified statement.", small));
            doc.close();
            return out.toByteArray();
        } catch (DocumentException | java.io.IOException e) {
            throw new IllegalStateException("PDF generation failed", e);
        }
    }
}
