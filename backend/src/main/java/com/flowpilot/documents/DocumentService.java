/**
 * Custom, printable layouts for personal financial records. Values come only from the user's own linked records (ownership is
 * re-checked here) or from text they type. A fixed disclaimer is always printed; documents are never presented as official.
 */
@Service
public class DocumentService {
    public static final String DISCLAIMER = "Personal record generated by FlowPilot. It is not an official tax invoice, a legally certified receipt, or a bank statement.";

    private final JdbcTemplate jdbc;
    private final FileStorageService files;
    private final FileValidator validator;
    private final FinancialAudit fin;

    public DocumentService(JdbcTemplate jdbc, FileStorageService files, FileValidator validator, FinancialAudit fin) { this.jdbc = jdbc; this.files = files; this.validator = validator; this.fin = fin; }

    public List<TemplateView> list(UUID userId, boolean archived) {
        return jdbc.query("select * from document_templates where (user_id is null or user_id = ?)" + (archived ? "" : " and archived_at is null") + " order by (user_id is null) desc, created_at, name", (rs, i) -> load(rs), userId);
    }

    @Transactional
    public TemplateView create(UUID userId, TemplateRequest r) {
        UUID id = jdbc.queryForObject("insert into document_templates (user_id, name, kind, title, brand_name, header_text, footer_text, accent_color, font_family, font_size, orientation) values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) returning id", UUID.class,
                userId, r.name().trim(), r.kind(), r.title().trim(), blank(r.brandName()), blank(r.headerText()), blank(r.footerText()), r.accentColor(), r.fontFamily(), r.fontSize(), r.orientation());
        writeFields(id, r.fields());
        return get(userId, id);
    }

    @Transactional
    public TemplateView update(UUID userId, UUID id, TemplateRequest r) {
        if (jdbc.update("update document_templates set name = ?, kind = ?, title = ?, brand_name = ?, header_text = ?, footer_text = ?, accent_color = ?, font_family = ?, font_size = ?, orientation = ? where id = ? and user_id = ? and archived_at is null",
                r.name().trim(), r.kind(), r.title().trim(), blank(r.brandName()), blank(r.headerText()), blank(r.footerText()), r.accentColor(), r.fontFamily(), r.fontSize(), r.orientation(), id, userId) == 0) throw ApiException.notFound("Template not found (built-in templates are read-only; duplicate them to edit).");
        jdbc.update("delete from document_fields where template_id = ?", id);
        writeFields(id, r.fields());
        return get(userId, id);
    }

    @Transactional
    public TemplateView duplicate(UUID userId, UUID id) {
        TemplateView t = get(userId, id);
        return create(userId, new TemplateRequest(t.name() + " (copy)", t.kind(), t.title(), t.brandName(), t.headerText(), t.footerText(), t.accentColor(), t.fontFamily(), t.fontSize(), t.orientation(), t.fields()));
    }

    @Transactional
    public void setArchived(UUID userId, UUID id, boolean archived) {
        if (jdbc.update("update document_templates set archived_at = " + (archived ? "now()" : "null") + " where id = ? and user_id = ?", id, userId) == 0) throw ApiException.notFound("Template not found.");
    }

    @Transactional
    public TemplateView setLogo(UUID userId, UUID id, MultipartFile file) {
        if (jdbc.queryForObject("select count(*) from document_templates where id = ? and user_id = ? and archived_at is null", Integer.class, id, userId) == 0) throw ApiException.notFound("Template not found.");
        var v = validator.validate(file, Set.of(Kind.PNG, Kind.JPEG), 1024 * 1024);
        UUID fileId = files.storePrivate(userId, "DOCUMENT", v).id();
        jdbc.update("update document_templates set logo_file_id = ? where id = ?", fileId, id);
        return get(userId, id);
    }

    @Transactional
    public TemplateView removeLogo(UUID userId, UUID id) {
        if (jdbc.update("update document_templates set logo_file_id = null where id = ? and user_id = ?", id, userId) == 0) throw ApiException.notFound("Template not found.");
        return get(userId, id);
    }

    public Preview preview(UUID userId, UUID templateId, GenerateRequest g) {
        TemplateView t = get(userId, templateId);
        return new Preview(t, resolve(userId, t, g), DISCLAIMER);
    }

    @Transactional
    public byte[] pdf(UUID userId, UUID templateId, GenerateRequest g) {
        TemplateView t = get(userId, templateId);
        List<ResolvedField> fields = resolve(userId, t, g);
        byte[] bytes = render(userId, t, fields);
        UUID docId = jdbc.queryForObject("insert into generated_documents (user_id, template_id, transaction_id, payment_id, sha256) values (?, ?, ?, ?, ?) returning id", UUID.class, userId, templateId, g.transactionId(), g.paymentId(), sha(bytes));
        fin.record(userId, userId, "DOCUMENT_EXPORTED", "DOCUMENT", docId, t.title() + " (" + t.name() + ")", null, g.transactionId() != null ? "transaction " + g.transactionId() : g.paymentId() != null ? "payment " + g.paymentId() : "manual");
        return bytes;
    }

    // ------------------------------------------------------------------ resolving values

    List<ResolvedField> resolve(UUID userId, TemplateView t, GenerateRequest g) {
        boolean needsTx = t.fields().stream().anyMatch(f -> f.source().startsWith("TX_")), needsPay = t.fields().stream().anyMatch(f -> f.source().startsWith("PAY_"));
        if (needsTx && g.transactionId() == null) throw ApiException.badRequest("TRANSACTION_REQUIRED", "This layout uses transaction details. Choose a transaction to link.");
        if (needsPay && g.paymentId() == null) throw ApiException.badRequest("PAYMENT_REQUIRED", "This layout uses payment details. Choose a payment to link.");
        Map<String, String> tx = g.transactionId() == null ? Map.of() : transaction(userId, g.transactionId());
        Map<String, String> pay = g.paymentId() == null ? Map.of() : payment(userId, g.paymentId());
        String name = jdbc.queryForObject("select full_name from user_profiles where user_id = ?", String.class, userId);
        Map<String, String> manual = g.manual() == null ? Map.of() : g.manual();
        List<ResolvedField> out = new ArrayList<>();
        int pos = 0;
        for (FieldDef f : t.fields()) {
            pos++;
            String v = switch (f.source()) {
                case "USER_NAME" -> name;
                case "TODAY" -> LocalDate.now(ZoneOffset.UTC).toString();
                case "MANUAL" -> clean(manual.get("m" + pos));
                case "PAY_REFERENCE", "PAY_AMOUNT", "PAY_PARTIES", "PAY_STATUS" -> pay.getOrDefault(f.source(), "—");
                default -> tx.getOrDefault(f.source(), "—");
            };
            out.add(new ResolvedField(f.label(), v == null || v.isBlank() ? "—" : v, f.source()));
        }
        return out;
    }

    private Map<String, String> transaction(UUID userId, UUID id) {
        var rows = jdbc.queryForList("select t.occurred_on, t.merchant, t.description, c.name as category, (select string_agg(a.name, ', ') from ledger_entries e join accounts a on a.id = e.account_id where e.transaction_id = t.id) as accounts, "
                + "(select coalesce(sum(case when t.type = 'TRANSFER' then greatest(e.amount, 0) else abs(e.amount) end), 0) from ledger_entries e where e.transaction_id = t.id) as amount, (select min(e.currency) from ledger_entries e where e.transaction_id = t.id) as currency "
                + "from transactions t left join categories c on c.id = t.category_id where t.id = ? and t.user_id = ?", id, userId);
        if (rows.isEmpty()) throw ApiException.notFound("Transaction not found.");
        var r = rows.get(0);
        Map<String, String> m = new HashMap<>();
        m.put("TX_DATE", String.valueOf(r.get("occurred_on"))); m.put("TX_MERCHANT", str(r.get("merchant"))); m.put("TX_DESCRIPTION", str(r.get("description"))); m.put("TX_CATEGORY", str(r.get("category")));
        m.put("TX_ACCOUNT", str(r.get("accounts"))); m.put("TX_AMOUNT", ((BigDecimal) r.get("amount")).setScale(2, java.math.RoundingMode.HALF_UP).toPlainString() + " " + str(r.get("currency")));
        return m;
    }

    private Map<String, String> payment(UUID userId, UUID id) {
        var rows = jdbc.queryForList("select p.reference, p.amount, p.currency, p.status, pr.full_name as payer, pe.full_name as payee from payments p join user_profiles pr on pr.user_id = p.payer_id join user_profiles pe on pe.user_id = p.payee_id where p.id = ? and (p.payer_id = ? or p.payee_id = ?)", id, userId, userId);
        if (rows.isEmpty()) throw ApiException.notFound("Payment not found.");
        var r = rows.get(0);
        return Map.of("PAY_REFERENCE", str(r.get("reference")), "PAY_AMOUNT", ((BigDecimal) r.get("amount")).toPlainString() + " " + r.get("currency") + " (simulated)", "PAY_PARTIES", r.get("payer") + " → " + r.get("payee"), "PAY_STATUS", str(r.get("status")));
    }

    // ------------------------------------------------------------------ PDF

    private byte[] render(UUID userId, TemplateView t, List<ResolvedField> fields) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Document doc = new Document(t.orientation().equals("LANDSCAPE") ? PageSize.A4.rotate() : PageSize.A4, 48, 48, 48, 48);
            PdfWriter.getInstance(doc, out);
            doc.open();
            String family = switch (t.fontFamily()) { case "TIMES" -> FontFactory.TIMES_ROMAN; case "COURIER" -> FontFactory.COURIER; default -> FontFactory.HELVETICA; };
            String bold = switch (t.fontFamily()) { case "TIMES" -> FontFactory.TIMES_BOLD; case "COURIER" -> FontFactory.COURIER_BOLD; default -> FontFactory.HELVETICA_BOLD; };
            java.awt.Color accent = java.awt.Color.decode(t.accentColor());
            Font title = FontFactory.getFont(bold, t.fontSize() + 9, accent), body = FontFactory.getFont(family, t.fontSize()), label = FontFactory.getFont(bold, t.fontSize()), small = FontFactory.getFont(family, Math.max(7, t.fontSize() - 3), java.awt.Color.DARK_GRAY);
            if (t.hasLogo()) {
                UUID logo = jdbc.queryForObject("select logo_file_id from document_templates where id = ?", UUID.class, t.id());
                if (logo != null) { try { Image img = Image.getInstance(files.readAuthorised(logo).bytes()); img.scaleToFit(130, 48); doc.add(img); } catch (Exception ignored) { /* a broken logo never blocks the document */ } }
            }
            if (t.brandName() != null) doc.add(new Paragraph(t.brandName(), label));
            doc.add(new Paragraph(t.title(), title));
            if (t.headerText() != null) doc.add(new Paragraph(t.headerText(), small));
            doc.add(new Paragraph(" "));
            PdfPTable table = new PdfPTable(new float[]{1.2f, 2f});
            table.setWidthPercentage(100);
            for (ResolvedField f : fields) {
                PdfPCell l = new PdfPCell(new Phrase(f.label(), label)), v = new PdfPCell(new Phrase(f.value(), body));
                l.setPadding(7); v.setPadding(7); l.setBorderColor(java.awt.Color.LIGHT_GRAY); v.setBorderColor(java.awt.Color.LIGHT_GRAY);
                v.setHorizontalAlignment(Element.ALIGN_LEFT); table.addCell(l); table.addCell(v);
            }
            doc.add(table);
            doc.add(new Paragraph(" "));
            if (t.footerText() != null) doc.add(new Paragraph(t.footerText(), small));
            doc.add(new Paragraph(DISCLAIMER, FontFactory.getFont(family, Math.max(7, t.fontSize() - 3), java.awt.Color.RED)));
            doc.close();
            return out.toByteArray();
        } catch (Exception e) {
            throw new IllegalStateException("PDF generation failed", e);
        }
    }

    // ------------------------------------------------------------------ helpers

    private TemplateView get(UUID userId, UUID id) {
        return jdbc.query("select * from document_templates where id = ? and (user_id is null or user_id = ?)", (rs, i) -> load(rs), id, userId).stream().findFirst().orElseThrow(() -> ApiException.notFound("Template not found."));
    }

    private TemplateView load(java.sql.ResultSet rs) throws java.sql.SQLException {
        UUID id = rs.getObject("id", UUID.class);
        List<FieldDef> fields = jdbc.query("select label, source from document_fields where template_id = ? order by position", (r, i) -> new FieldDef(r.getString(1), r.getString(2)), id);
        return new TemplateView(id, rs.getString("name"), rs.getString("kind"), rs.getString("title"), rs.getString("brand_name"), rs.getString("header_text"), rs.getString("footer_text"), rs.getString("accent_color"), rs.getString("font_family"),
                rs.getInt("font_size"), rs.getString("orientation"), rs.getObject("logo_file_id") != null, rs.getObject("user_id") == null, rs.getTimestamp("archived_at") != null, fields);
    }

    private void writeFields(UUID id, List<FieldDef> fields) {
        int pos = 1;
        for (FieldDef f : fields) jdbc.update("insert into document_fields (template_id, position, label, source) values (?, ?, ?, ?)", id, pos++, f.label().trim(), f.source());
    }

    private static String clean(String s) { return s == null ? null : s.replaceAll("[\\p{Cntrl}&&[^\\n]]", "").trim(); }
    private static String blank(String s) { return s == null || s.isBlank() ? null : s.trim(); }
    private static String str(Object o) { return o == null ? "—" : o.toString(); }
    private static String sha(byte[] b) { try { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(b)); } catch (java.security.NoSuchAlgorithmException e) { throw new IllegalStateException(e); } }
}
